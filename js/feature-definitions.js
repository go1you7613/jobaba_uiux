  function esc(value){
    return String(value).replace(/[&<>"']/g,function(c){
      return {"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c];
    });
  }

  function currentFile(){
    return window.location.pathname.split("/").pop() || "index.html";
  }

  function mergeState(base, custom){
    var result={}, key;
    for(key in base) if(Object.prototype.hasOwnProperty.call(base,key)) result[key]=base[key];
    custom=custom||{};
    for(key in custom) if(Object.prototype.hasOwnProperty.call(custom,key)) result[key]=custom[key];
    return result;
  }

  function getContext(){
    var key=FILE_MAP[currentFile()];
    var definition=DEFINITIONS[key];
    if(!definition) return null;
    var user=definition.state==="common"?"common":(document.body.getAttribute("data-user")||"guest");
    if(!BASE_STATES[user]) user="guest";
    var state=mergeState(BASE_STATES[user],definition.states&&definition.states[user]);
    var features=(definition.features||[]).slice();
    if(definition.stateFeatures&&definition.stateFeatures[user]) features=features.concat(definition.stateFeatures[user]);
    return {definition:definition,state:state,user:user,features:features};
  }

  function featureItems(features){
    return features.map(function(feature,index){
      var num=String(index+1);if(num.length<2) num="0"+num;
      return '<li><span class="feature-modal__num">'+num+'</span><div><strong>'+esc(feature[0])+'</strong><p>'+esc(feature[1])+'</p></div></li>';
    }).join("");
  }

  function reviewItems(items){
    return (items||[]).map(function(item){return '<li>'+esc(item)+'</li>';}).join("");
  }

  function ensureButton(){
    if(document.querySelector("[data-feature-modal-open]")) return;
    var right=document.querySelector(".proto-bar__right");
    if(!right) return;
    var button=document.createElement("button");
    button.type="button";
    button.className="proto-bar__btn proto-bar__feature-btn";
    button.setAttribute("data-feature-modal-open","");
    button.setAttribute("aria-haspopup","dialog");
    button.textContent="기능정의 보기";
    var page=right.querySelector(".proto-bar__page");
    right.insertBefore(button,page||right.firstChild);
  }

