  function openModal(trigger){
    var modal=document.getElementById("feature-definition-modal");
    if(!modal) return;
    returnFocus=trigger||document.activeElement;
    modal.classList.add("is-open");
    modal.setAttribute("aria-hidden","false");
    document.body.classList.add("is-modal-open");
    var close=modal.querySelector("[data-feature-modal-close]");
    if(close) close.focus();
  }

  function closeModal(){
    var modal=document.getElementById("feature-definition-modal");
    if(!modal||!modal.classList.contains("is-open")) return;
    modal.classList.remove("is-open");
    modal.setAttribute("aria-hidden","true");
    document.body.classList.remove("is-modal-open");
    if(returnFocus&&document.contains(returnFocus)) returnFocus.focus();
    returnFocus=null;
  }

  function init(){
    var context=getContext();
    if(!context) return;
    ensureButton();
    ensureModal(context);
  }

  document.addEventListener("click",function(event){
    var opener=event.target.closest("[data-feature-modal-open]");
    if(opener){event.preventDefault();openModal(opener);return;}
    if(event.target.closest("[data-feature-modal-close]")||event.target.classList.contains("modal--feature")) closeModal();
  });

  document.addEventListener("keydown",function(event){
    if(event.key==="Escape") closeModal();
  });

  document.addEventListener("DOMContentLoaded",function(){
    window.setTimeout(init,0);
  });

  window.JobabaFeatureDefinitions={init:init};
